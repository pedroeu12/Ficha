    private val byIdMap: Map<String, SpellDef> = ALL.associateBy { it.id }

    fun byId(id: String): SpellDef? = byIdMap[id]

    /** Every spell on a class's list at exactly [level]. */
    fun forClass(classId: String, level: Int): List<SpellDef> =
        ALL.filter { classId in it.classes && it.level == level }.sortedBy { it.name }

    /** Every spell on a class's list up to and including [maxLevel]. */
    fun forClassUpTo(classId: String, maxLevel: Int): List<SpellDef> =
        ALL.filter { classId in it.classes && it.level in 0..maxLevel }
            .sortedWith(compareBy({ it.level }, { it.name }))

    fun cantripsForClass(classId: String): List<SpellDef> = forClass(classId, 0)

    /** The highest spell level the catalog carries, used to decide when to offer manual entry. */
    const val MAX_CATALOGUED_LEVEL: Int = 5
